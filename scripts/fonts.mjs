// Builds src/fonts/*.woff2 and src/fonts.css: the site's three typefaces cut down to the
// characters the site actually uses (all of printable ASCII, plus every other character
// found in the content, the interface strings and the page itself). Turkish needs only a
// handful of "extended Latin" letters, so those files shrink from ~60 KB to a few KB.
// Run again after adding text with new characters: npm run fonts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/fonts');

// every character the site can show
const sources = ['index.html', 'src/i18n.js', 'src/labels.js', 'src/hobbies.js', 'src/travel/travel.js'];
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const contentFiles = walk(path.join(root, 'public/content')).filter((f) => /\.(md|json)$/.test(f) && !f.includes('/map/'));
let text = [...sources.map((f) => path.join(root, f)), ...contentFiles].map((f) => fs.readFileSync(f, 'utf8')).join('');
for (let c = 0x20; c < 0x7f; c++) text += String.fromCharCode(c); // all of ASCII
text += 'ÇĞİÖŞÜçğıöşüÂâÎîÛûÉéÈèÀàÊêÔôËëÏïÄäÑñ“”‘’–—…•·→←↗₺€£$%&@ ';
text += text.toLocaleUpperCase('tr') + text.toLocaleLowerCase('tr') + text.toUpperCase();
const chars = [...new Set([...text])].filter((ch) => ch.codePointAt(0) >= 0x20).join('');

// fontsource's split: latin and latin-ext (anything outside them is left to fallbacks)
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const ranges = (r) => r.split(',').map((x) => x.replace('U+', '').split('-').map((h) => parseInt(h, 16))).map(([a, b = a]) => [a, b]);
const inLatin = (cp) => ranges(LATIN).some(([a, b]) => cp >= a && cp <= b);
const latinChars = [...chars].filter((ch) => inLatin(ch.codePointAt(0))).join('');
const extChars = [...chars].filter((ch) => !inLatin(ch.codePointAt(0))).join('');
const extRange = [...extChars].map((ch) => 'U+' + ch.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')).join(',');

const nm = (p) => path.join(root, 'node_modules', p);
const faces = [
  { family: 'Fraunces Variable', style: 'normal', weight: '100 900', latin: nm('@fontsource-variable/fraunces/files/fraunces-latin-opsz-normal.woff2'), ext: nm('@fontsource-variable/fraunces/files/fraunces-latin-ext-opsz-normal.woff2'), name: 'fraunces' },
  { family: 'Fraunces Variable', style: 'italic', weight: '100 900', latin: nm('@fontsource-variable/fraunces/files/fraunces-latin-opsz-italic.woff2'), ext: nm('@fontsource-variable/fraunces/files/fraunces-latin-ext-opsz-italic.woff2'), name: 'fraunces-italic' },
  ...[500, 700, 800].map((w) => ({ family: 'Big Shoulders Display', style: 'normal', weight: String(w), latin: nm(`@fontsource/big-shoulders-display/files/big-shoulders-display-latin-${w}-normal.woff2`), ext: nm(`@fontsource/big-shoulders-display/files/big-shoulders-display-latin-ext-${w}-normal.woff2`), name: `big-shoulders-${w}` })),
  ...[400, 500].map((w) => ({ family: 'IBM Plex Mono', style: 'normal', weight: String(w), latin: nm(`@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-${w}-normal.woff2`), ext: nm(`@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-ext-${w}-normal.woff2`), name: `plex-mono-${w}` })),
];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
let css = '/* Generated by scripts/fonts.mjs: subsets of Fraunces, Big Shoulders Display and IBM Plex Mono (SIL OFL). */\n';
let before = 0;
let after = 0;
for (const f of faces) {
  for (const [part, file, keep, range] of [['latin', f.latin, latinChars, LATIN], ['ext', f.ext, extChars, extRange]]) {
    if (!keep) continue;
    const src = fs.readFileSync(file);
    const sub = await subsetFont(src, keep, { targetFormat: 'woff2' });
    const name = `${f.name}-${part}.woff2`;
    fs.writeFileSync(path.join(out, name), sub);
    before += src.length;
    after += sub.length;
    css += `@font-face {\n  font-family: '${f.family}';\n  font-style: ${f.style};\n  font-display: swap;\n  font-weight: ${f.weight};\n  src: url(./fonts/${name}) format('woff2');\n  unicode-range: ${range};\n}\n`;
  }
}
fs.writeFileSync(path.join(root, 'src/fonts.css'), css);
console.log(`${chars.length} characters; extended-Latin ones: ${extChars}`);
console.log(`fonts: ${Math.round(before / 1024)} KB -> ${Math.round(after / 1024)} KB`);
